export const TRANSLATIONS: Record<Locale, Strings> = { en, es, fr, de, it, pt, nl, ja, ko, 'zh-Hans': zhHans, 'zh-Hant': zhHant };

/** A file size in the language's own units and number format. */
export function formatSize(bytes: number, locale: Locale, strings: Strings): string {
  const [kb, mb] = strings.units;
  if (bytes < 1024 * 1024) return `${Math.max(1, Math.round(bytes / 1024))} ${kb}`;
  return `${new Intl.NumberFormat(locale, { maximumFractionDigits: 1, minimumFractionDigits: 1 }).format(bytes / (1024 * 1024))} ${mb}`;
}
