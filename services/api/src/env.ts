import type { ConversationRoom, WorkspaceHub } from '@openchat/realtime';
import type { AuthGuard } from './auth-guard';

export interface Env {
  DB: D1Database;
  ATTACHMENTS: R2Bucket;
  ASSETS: Fetcher;
  WORKSPACE_HUB: DurableObjectNamespace<WorkspaceHub>;
  CONVERSATION_ROOM: DurableObjectNamespace<ConversationRoom>;
  AUTH_GUARD: DurableObjectNamespace<AuthGuard>;
  /** JSON: { active: { kid, privateKey, publicKey }, retired?: [{ kid, publicKey }] }. Worker secret. */
  AUTH_SIGNING_KEY?: string;
  /** `resend`, `cloudflare`, or `console` for local development only. With none, email jobs retry and dead-letter. */
  EMAIL_PROVIDER?: string;
  /** Worker secret. */
  RESEND_API_KEY?: string;
  /** Cloudflare Email Service. Only rendered for a deployment that chose it, restricted to its sending address. */
  EMAIL?: SendEmail;
  /** The sending address for system email, on a domain verified with the provider. */
  SYSTEM_EMAIL_FROM?: string;
  NOTIFICATIONS_QUEUE: Queue;
  /** Optional, all four together: with any missing, this installation has no push and messaging is unaffected. */
  RELAY_URL?: string;
  RELAY_ID?: string;
  /** Comma-separated. The apps this relay can reach, which the app compares with its own. */
  RELAY_BUNDLE_IDS?: string;
  /** JSON: { active: { kid, privateKey, publicKey } }. Worker secret. Signs requests and grants to the relay. */
  RELAY_SIGNING_KEY?: string;
  EMAIL_QUEUE: Queue;
  /** Worker secret, generated by `oc deploy`. Without it the operator health checks under /health/* do not exist. */
  OPERATOR_TOKEN?: string;
  /** For /.well-known/security.txt: the operator's mailto: or https: contacts, comma separated. Without one, it answers 404. */
  SECURITY_CONTACT?: string;
  /** For /.well-known/security.txt: an https: URL of the operator's disclosure policy. */
  SECURITY_POLICY?: string;
  JOBS_QUEUE: Queue;
  /** Worker secret, with its pair. Without both, no website can require Turnstile. */
  TURNSTILE_SECRET_KEY?: string;
  TURNSTILE_SITE_KEY?: string;
  /** Optional. See ABUSE_LIMITS in @openchat/shared for what each means and its default. */
  LIMIT_MESSAGES_PER_WEBSITE_PER_DAY?: string;
  LIMIT_MESSAGES_PER_IP_PER_MINUTE?: string;
  LIMIT_MESSAGE_MAX_CHARS?: string;
  LIMIT_IPV6_PREFIX?: string;
  /** Optional: Analytics Engine has to be enabled per account. See tooling/cli/src/render-config.ts. */
  METRICS?: AnalyticsEngineDataset;
}
